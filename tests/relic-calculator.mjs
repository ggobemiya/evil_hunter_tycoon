import assert from 'node:assert/strict';
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
const root = process.argv[2] || fileURLToPath(new URL('../', import.meta.url));
const load = async file => import('data:text/javascript;base64,' + Buffer.from(fs.readFileSync(`${root}/src/${file}`, 'utf8')).toString('base64'));
const { weeklyIncome, estimateRandom, daysNeeded, bounded } = await load('relicCalculator.js');
const { temperingOptions, personalities } = await load('referenceData.js');
const { relics, relicLevelUp } = await load('relicData.js');
assert.equal(temperingOptions.length, 35);
assert.equal(temperingOptions.reduce((s, o) => s + o.chance, 0), 100);
assert.equal(personalities.length, 33);
assert.equal(new Set(personalities.map(p => p.name)).size, 33);
assert.equal(relics.length * (1 + relicLevelUp.reduce((s, r) => s + r.count, 0)), 8130);
const input = { worldTier: 1, worldTimes: 7, heroTier: 5, heroTimes: 2, field: 2, expeditions: 10, expeditionTokens: 7, excavationHours: 6, challenger: 2, medal: 2, extra: 50 };
assert.deepEqual(weeklyIncome(input).map(r => r[1]), [280, 40, 70, 98, 21, 200, 200, 50]);
assert.equal(daysNeeded(1000, 0, 700), 10);
assert.equal(daysNeeded(1000, 1000, 0), 0);
assert.equal(daysNeeded(1000, 0, 0), null);
assert.equal(bounded(-1, 1, 5, true), 1);
assert.equal(bounded(6, 1, 5, true), 5);
assert.equal(bounded(NaN, 1, 5, true), 1);
assert.equal(estimateRandom(Array(30).fill(271)).mean, 0);
assert.equal(estimateRandom([270]).mean, 10);
const last = Array(30).fill(271); last[0] = 270;
const lastEstimate = estimateRandom(last, 10000);
// Geometric(1/30): one useful draw costs 10, 29 expected duplicates cost 5 each.
assert.ok(Math.abs(lastEstimate.mean - 155) < 6, JSON.stringify(lastEstimate));
const fresh = estimateRandom(Array(30).fill(0));
assert.ok(fresh.mean > 81300 && fresh.mean < 120000);
assert.deepEqual(fresh, estimateRandom(Array(30).fill(0)));
console.log('Passed: data counts, probability totals, income, bounds, zero income, completed collection, random refund model and deterministic estimates.');
console.log(JSON.stringify({ fresh, lastEstimate }));

assert.equal(weeklyIncome({ ...input, excavationHours: 24 })[4][1], 84);
assert.equal(weeklyIncome({ ...input, excavationHours: 48 })[4][1], 84);
assert.equal(weeklyIncome({ ...input, excavationHours: 0 })[4][1], 0);
assert.equal(weeklyIncome({ ...input, medal: 0 })[6][1], 0);

const { STORAGE_KEY, normalizeState, loadState, saveState } = await load('relicStorage.js');
const names = relics.map(r => r.name);
const defaults = normalizeState(null, names);
assert.equal(defaults.owned.reduce((a, b) => a + b, 0), 1715);
assert.equal(weeklyIncome(defaults.settings).reduce((sum, row) => sum + row[1], 0), 837);
const memory = new Map();
const storage = { getItem: key => memory.get(key) ?? null, setItem: (key, value) => memory.set(key, value) };
assert.deepEqual(loadState(storage, names).settings, defaults.settings);
const modified = structuredClone(defaults);
modified.settings.worldTier = 1; modified.wallet = 116; modified.owned[0] = 99;
assert.equal(saveState(storage, modified, names), true);
const restored = loadState(storage, names);
assert.equal(restored.settings.worldTier, 1);
assert.equal(restored.wallet, 116);
assert.equal(restored.owned[0], 99);
assert.equal(loadState(storage, names.slice().reverse()).owned.at(-1), 99);
memory.set(STORAGE_KEY, '{broken');
assert.equal(loadState(storage, names).error, true);
assert.deepEqual(loadState(storage, names).owned, defaults.owned);
const denied = { getItem() { throw Error('blocked'); }, setItem() { throw Error('quota'); } };
assert.equal(loadState(denied, names).error, true);
assert.equal(saveState(denied, modified, names), false);
assert.equal(normalizeState({ settings: { worldTier: -8 }, wallet: 'invalid' }, names).settings.worldTier, 1);
console.log('Passed: defaults (837 tokens/week, 1715 owned), save/restore, name-based restoration, corrupt data and unavailable storage.');

